// Reads ./music and writes src/core/presets.ts. Only names and times are
// emitted -- no audio ships with the app; the user supplies their own files.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { albumKey, minutesToHour, parseTrackName } from '../src/core/naming.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const musicDir = join(root, 'music');

const albums = readdirSync(musicDir)
  .filter((name) => statSync(join(musicDir, name)).isDirectory())
  .sort();

const stations = albums.map((dir) => {
  const files = readdirSync(join(musicDir, dir))
    .filter((f) => /\.(flac|mp3|m4a|ogg|opus|wav|aac)$/i.test(f))
    .sort();
  const parsedDir = parseTrackName(dir);
  const name = parsedDir.album ?? dir;
  const programs = files
    .map((file) => {
      const parsed = parseTrackName(file);
      return { title: parsed.title, minutes: parsed.timeOfDayMinutes };
    })
    .filter((p) => p.minutes !== null)
    .sort((a, b) => a.minutes - b.minutes);
  return {
    id: `st-${albumKey(name)}`,
    name,
    albumKey: albumKey(name),
    programs: programs.map((p, n) => ({
      id: `st-${albumKey(name)}-p${n + 1}`,
      name: p.title,
      startHour: Number(minutesToHour(p.minutes).toFixed(6)),
      trackIds: [],
    })),
  };
});

// Numbered along the dial, densely, so albums without a schedule don't leave gaps.
const withPrograms = stations.filter((s) => s.programs.length > 0);
withPrograms.forEach((s, i) => { s.channel = i + 1; });
const skipped = stations.filter((s) => s.programs.length === 0);

const body = `// GENERATED by tools/make-presets.mjs -- do not edit by hand.
// Station and daypart names with their broadcast times. No audio is bundled;
// the listener imports their own files and they are matched into these slots.
import type { Station } from './types';

export const STATION_PRESETS: Station[] = ${JSON.stringify(withPrograms, null, 2)};

/** Albums with no time-stamped tracks, so they aren't stations. */
export const NON_STATION_ALBUMS: string[] = ${JSON.stringify(skipped.map((s) => s.name), null, 2)};
`;

writeFileSync(join(root, 'src/core/presets.ts'), body);
console.log(`${withPrograms.length} stations, ${withPrograms.reduce((n, s) => n + s.programs.length, 0)} dayparts`);
for (const s of withPrograms) {
  console.log(`  ${s.channel}  ${s.name}: ${s.programs.map((p) => `${p.startHour.toFixed(2)} ${p.name}`).join(' | ')}`);
}
if (skipped.length) console.log(`skipped (no timestamps): ${skipped.map((s) => s.name).join(', ')}`);
